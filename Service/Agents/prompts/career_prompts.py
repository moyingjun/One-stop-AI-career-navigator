def build_career_user_prompt(resume_text: str, user_confusion: str) -> str:
    """
    组装职业规划的用户侧 Prompt。

    参数：
        resume_text    — 候选人简历文本
        user_confusion — 用户的职业困惑或期望

    返回：
        完整的用户 Prompt 字符串
    """
    return f"【候选人简历】：\n{resume_text}\n\n【职业困惑/期望】：\n{user_confusion}"


def build_suggestions_user_prompt(resume_text: str) -> str:
    """
    组装职业推荐问题的用户侧 Prompt。

    参数：
        resume_text — 候选人简历文本

    返回：
        完整的用户 Prompt 字符串
    """
    return (
        "请根据以下简历，推测该候选人目前最可能面临的4个职业发展困惑或面试痛点。"
        "必须且只能返回一个合法的 JSON 数组。单句不超过15个字。绝对不要输出其他废话！"
        f"简历内容：\n{resume_text}"
    )
